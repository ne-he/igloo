// Bangkitkan atlas MSDF IBM Plex Mono Medium (blueprint 8.2 aset 19, 5.6).
// Pakai:  node tools/fonts/gen_msdf.mjs
// Hasil:  public/assets/fonts/plexmono-msdf.png (lossless) + plexmono-msdf.json (format BMFont + blok metrics)
//
// Parameter meniru atlas igloo: size 42, distance range 4. Beda: igloo pakai msdf-atlas-gen dengan grid
// sel 64 px (makanya trik scramble geser uv 1/8 jalan di sana), kita pakai msdf-bmfont-xml yang mem-pack
// glyph rapat (maxrects). Karena itu scramble di shader menukar rect glyph lewat tabel, bukan geser uv.
// Font: IBM Plex Mono (OFL-1.1) dari paket @ibm/plex-mono. opentype.js bisa baca WOFF langsung,
// jadi tidak perlu konversi ke TTF.
import { createRequire } from 'node:module'
import { fileURLToPath } from 'node:url'
import fs from 'node:fs'
import path from 'node:path'

const require = createRequire(import.meta.url)
const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..', '..')
const FONT = path.join(ROOT, 'node_modules/@ibm/plex-mono/fonts/complete/woff/IBMPlexMono-Medium.woff')
const OUT_DIR = path.join(ROOT, 'public/assets/fonts')
const NAME = 'plexmono-msdf'

const SIZE = 42
const RANGE = 4

// ASCII cetak (32..126) + simbol tambahan. Urutan ini juga urutan tabel scramble di runtime.
let charset = ''
for (let c = 32; c <= 126; c++) charset += String.fromCharCode(c)
charset += '©®·‘’“”€' // © ® · ‘ ’ “ ” €

const generateBMFont = require('msdf-bmfont-xml')
// opentype.js ikut terpasang sebagai dependensi msdf-bmfont-xml, dipakai untuk metrik tambahan.
const opentype = createRequire(require.resolve('msdf-bmfont-xml'))('opentype.js')

const opt = {
  outputType: 'json',
  filename: path.join(OUT_DIR, NAME),
  fontSize: SIZE,
  distanceRange: RANGE,
  fieldType: 'msdf',
  textureSize: [512, 1024],
  texturePadding: 2,
  // Wajib diisi: kalau kosong, library membulatkan SEMUA angka ke integer (xadvance 25.2 jadi 25,
  // base 32.76 jadi 33), dan teks panjang jadi meleset sekitar 1 px tiap 20 huruf.
  roundDecimal: 4,
  smartSize: true,
  pot: true,
  charset,
}

fs.mkdirSync(OUT_DIR, { recursive: true })

generateBMFont(FONT, opt, (err, textures, font) => {
  if (err) {
    console.error(err)
    process.exit(1)
  }
  if (textures.length !== 1) {
    console.error(`atlas pecah jadi ${textures.length} halaman, perbesar textureSize`)
    process.exit(1)
  }
  fs.writeFileSync(path.join(OUT_DIR, `${NAME}.png`), textures[0].texture)

  const data = JSON.parse(font.data)
  data.pages = [`${NAME}.png`]
  // Urutkan glyph per kode supaya file stabil antar run (urutan pack bisa beda).
  data.chars.sort((a, b) => a.id - b.id)

  // Metrik dalam satuan em (font size 1), dibaca MsdfFont untuk layout dan posisi UI per cap height.
  const ot = opentype.loadSync(FONT)
  const upm = ot.unitsPerEm
  const os2 = ot.tables.os2
  data.metrics = {
    emSize: SIZE,
    unitsPerEm: upm,
    lineHeight: (os2.sTypoAscender - os2.sTypoDescender + os2.sTypoLineGap) / upm,
    ascender: os2.sTypoAscender / upm,
    descender: os2.sTypoDescender / upm,
    capHeight: os2.sCapHeight / upm,
    xHeight: os2.sxHeight / upm,
  }
  data.info.source = 'IBM Plex Mono Medium (SIL OFL 1.1), generated by tools/fonts/gen_msdf.mjs'
  fs.writeFileSync(path.join(OUT_DIR, `${NAME}.json`), JSON.stringify(data))

  const missing = Array.from(charset).filter((ch) => !data.chars.some((c) => c.id === ch.codePointAt(0)))
  console.log(`atlas ${data.common.scaleW}x${data.common.scaleH}, ${data.chars.length} glyph, kerning ${data.kernings.length}`)
  console.log('metrics', data.metrics)
  if (missing.length) console.log('glyph hilang:', missing.join(' '))
})
